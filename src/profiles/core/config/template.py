"""Starter configuration template for ProFiles configuration files.

This module provides the canonical YAML template for ProFiles
configuration files. It is used by ``write_starter_config()`` and
``init_default_config()`` to generate fresh ``.profiles`` files.

Escaping rules inside ``STARTER_CONFIG_TEMPLATE`` (a regular, non-raw
string rendered with ``.format(cwd=...)``):

* every literal brace is doubled (``{{...}}``) and collapses to a single
  brace in the generated file — this is how ``{group:N}`` transform
  backreferences and ``{{token}}`` hook tokens end up in the file;
* ``{cwd}`` is the only single-brace placeholder and is substituted at
  write time;
* a regex escape wanted in the final YAML value (``\\d``) is written
  ``\\d`` in this source so the generated single-quoted YAML scalar
  keeps one backslash.
"""

