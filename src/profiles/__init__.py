def _resolve_version() -> str:
    """Return the package version.

    Resolution order: the hatch-vcs generated ``profiles._version``
    module (regenerated by every build and editable install, so it
    always matches the current tree), then installed package metadata
    (dist-info, for legacy installs without a version module), then a
    development sentinel for git-less source trees.
    """
    # The version module is regenerated by the build hook on every
    # build/editable install — it is never stale relative to the tree,
    # unlike dist-info which only updates on (re)install.
    try:
        from profiles._version import version as vcs_version
    except ImportError:
        pass
    else:
        return str(vcs_version)

    # Fallback: installed package metadata. The PEP 621 distribution name
    # is "profiles-app"; "profiles" covers legacy setuptools installs. The
    # import stays function-local (importlib.metadata is stdlib on every
    # supported Python) to keep ``import profiles`` cheap.
    from importlib.metadata import PackageNotFoundError, version

    try:
        try:
            return version("profiles-app")
        except PackageNotFoundError:
            return version("profiles")
    except Exception:
        # Not installed via pip, or metadata unreadable (permissions,
        # corrupted install, etc.)
        pass

    return "0.0.0-dev"


__version__ = _resolve_version()


def __getattr__(name: str):
    """Expose selected callables lazily (PEP 562).

    The Briefcase stub resolves ``profiles.main``; keep it a lazy attribute
    so ``import profiles`` stays cheap for headless/web usage.
    """
    if name == "main":
        from profiles.app import main as _main

        return _main
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
